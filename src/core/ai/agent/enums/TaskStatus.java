package ai.agent.enums;

/**
 * Task Status Enum
 * Defines the status of tasks in the task board
 */
public enum TaskStatus {
    /**
     * Pending - Task has been created but not yet started
     */
    PENDING,

    /**
     * In Progress - Task is currently being executed
     */
    IN_PROGRESS,

    /**
     * Completed - Task has been successfully completed
     */
    COMPLETED
}
